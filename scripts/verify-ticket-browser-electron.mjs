import {app,BrowserWindow,session} from 'electron';
import {join} from 'node:path';
import {mkdtempSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const load=createRequire(import.meta.url);
const [root,origin,output]=process.argv.slice(2);
const fixtureData=mkdtempSync(join(tmpdir(),'mc-ticket-browser-'));
app.setPath('userData',fixtureData);process.env.MC_USER_DATA_DIR=fixtureData;
app.whenReady().then(async()=>{
 const {configureIpcAllowedOrigins}=load(join(root,'dist-electron/electron/ipc-safe-handle.js'));
 const {registerPrBrowserHandlers}=load(join(root,'dist-electron/electron/pr-browser.js'));
 configureIpcAllowedOrigins([origin]);registerPrBrowserHandlers();
 const partition=session.fromPartition('persist:ticket-browser');
 await partition.protocol.handle('https',request=>new Response(`<!doctype html><html><meta charset="utf-8"><style>body{font:16px system-ui;background:#202124;color:#eee;padding:24px}a{color:#8ab4f8}button{font:inherit}</style><h1>Fixture Jira ${new URL(request.url).pathname.startsWith('/browse/')?'ticket detail':'search results'}</h1><p>Local fixture — no Jira account or provider requests.</p><a id="ticket" href="https://example.atlassian.net/browse/APP-3184">APP-3184 · billing-service task</a><p>Full description and Jira editing controls appear here in the real site.</p></html>`,{headers:{'content-type':'text/html; charset=utf-8'}}));
 const host=new BrowserWindow({width:1440,height:1000,show:true,webPreferences:{preload:join(root,'dist-electron/electron/preload.js'),contextIsolation:true,nodeIntegration:false,sandbox:false}});
 const run=source=>host.webContents.executeJavaScript(source,true);
 const wait=async check=>{const deadline=Date.now()+15000;while(Date.now()<deadline){if(await check())return;await new Promise(resolve=>setTimeout(resolve,80))}throw new Error('Timed out: '+String(check))};
 const click=selector=>run(`document.querySelector(${JSON.stringify(selector)})?.click()`);
 const view=()=>host.contentView.children.find(child=>child.webContents);
 const field=async(name,value)=>{await run(`document.querySelector('form[aria-label="Jira browser settings"] [name="${name}"]').focus()`);await host.webContents.insertText(value)};
 try{
  await host.loadURL(origin);
  await wait(()=>run(`!!document.querySelector('[aria-label="Show Jira tickets"]')`));
  await click('[aria-label="Show Jira tickets"]');
  await wait(()=>run(`document.body.textContent.includes('Configure tickets for mission-control')`));
  assert.equal(view(),undefined);
  writeFileSync(join(output,'empty.png'),(await host.webContents.capturePage()).toPNG());
  await click('.mc-ticket-empty button');
  await wait(()=>run(`!!document.querySelector('form[aria-label="Jira browser settings"] input[name="workspaceUrl"]')`));
  await field('workspaceUrl','https://example.atlassian.net');await field('project','Example Project');await field('keywords','billing service*');
  await click('form[aria-label="Jira browser settings"] button[type="submit"]');
  await wait(()=>run(`document.querySelector('form[aria-label="Jira browser settings"] button[type="submit"]').disabled===false`));
  writeFileSync(join(output,'settings.png'),(await host.webContents.capturePage()).toPNG());
  await click('#close-settings');await wait(()=>!!view()&&!view().webContents.isLoading());
  const guest=view();
  await wait(()=>run(`!!document.querySelector('.mc-ticket-footer button:disabled')`));
  assert.ok(guest.webContents.getURL().includes('jql='));
  assert.equal(guest.webContents.getLastWebPreferences().nodeIntegration,false);
  assert.equal(guest.webContents.getLastWebPreferences().sandbox,true);
  await guest.webContents.executeJavaScript(`document.querySelector('#ticket').click()`);
  await wait(()=>run(`document.querySelector('.mc-ticket-footer button')?.disabled===false`));
  assert.ok((await guest.webContents.executeJavaScript('document.body.textContent')).includes('Fixture Jira ticket detail'));
  writeFileSync(join(output,'jira-content.png'),(await guest.webContents.capturePage()).toPNG());
  await click('.mc-ticket-footer button');
  assert.deepEqual(await run('window.pasted'),['Implement ticket https://example.atlassian.net/browse/APP-3184']);
  writeFileSync(join(output,'ticket.png'),(await host.webContents.capturePage()).toPNG());
  await click('[aria-label="Hide tickets"]');await wait(()=>!guest.getVisible());
  await click('[aria-label="Show Jira tickets"]');await wait(()=>guest.getVisible());
  assert.equal(view().webContents.id,guest.webContents.id);
  assert.ok(guest.webContents.getURL().endsWith('/browse/APP-3184'));
  await click('.mc-ticket-browser-toolbar button:nth-child(4)');await wait(()=>guest.webContents.getURL().includes('jql=')&&!guest.webContents.isLoading());
  await wait(()=>run(`document.querySelector('.mc-ticket-footer button').disabled`));
  await guest.webContents.executeJavaScript(`history.pushState({},'', '/issues?jql=fixture&selectedIssue=APP-3356')`);
  await wait(()=>run(`document.querySelector('.mc-ticket-footer p').textContent==='APP-3356'`));
  await guest.webContents.loadURL('https://id.atlassian.com/login?selectedIssue=APP-3356');
  await wait(()=>run(`document.querySelector('.mc-ticket-footer button').disabled`));
  await click('[aria-label="Ticket settings"]');await wait(()=>!guest.getVisible());
  await click('#close-settings');await wait(()=>guest.getVisible());
  await run('window.switchProject()');await wait(()=>run(`document.body.textContent.includes('Configure tickets for operations')`));
  await wait(()=>!guest.getVisible());
  host.setSize(620,900);await new Promise(resolve=>setTimeout(resolve,200));
  writeFileSync(join(output,'narrow-empty.png'),(await host.webContents.capturePage()).toPNG());
  const prSession=session.fromPartition('persist:pr-browser');
  await prSession.protocol.handle('https',()=>new Response('<html><body>Fixture PR</body></html>',{headers:{'content-type':'text/html'}}));
  await partition.cookies.set({url:'https://example.atlassian.net',name:'fixture-session',value:'fixture-only',secure:true});
  assert.equal((await prSession.cookies.get({name:'fixture-session'})).length,0);
  await run(`window.electronAPI.prBrowser.show('fixture-pr','pr-mount','https://github.com/fixture/repo/pull/1',{x:10,y:10,width:300,height:300})`);
  await wait(()=>host.contentView.children.some(child=>child.webContents?.getURL().startsWith('https://github.com/')));
  assert.ok(host.contentView.children.find(child=>child.webContents?.getURL().startsWith('https://github.com/')).webContents.session===prSession);
  assert.equal(await run(`window.electronAPI.prBrowser.show('invalid','invalid','https://example.atlassian.net/issues',{x:10,y:10,width:300,height:300}).then(()=>false,()=>true)`),true);
  await run(`window.electronAPI.prBrowser.destroy('fixture-pr')`);
  writeFileSync(join(output,'result.json'),JSON.stringify({passed:true,network:'local fixtures only',checks:['unconfigured empty state','project-scoped settings save','native sandboxed WebContentsView','generated JQL search URL','selected ticket navigation','real xterm paste without Enter','hide/reopen retains browser','search results return','selectedIssue detection','SSO URL disables terminal actions','settings hides native view','project switching isolates filters']},null,2));
  console.log('Ticket browser: native Electron, project filters, navigation, xterm paste, overlays, and isolation passed with local fixtures.');
 }finally{host.destroy()}
}).then(()=>app.quit()).catch(error=>{console.error(error);app.exit(1)});
